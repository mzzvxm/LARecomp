// Pads a hex string with zero bytes to `bytes` bytes (the tournament answer's definition file is mostly zeros).
inline std::string PadHexTo(std::string hex, size_t bytes) {
    if (hex.size() < bytes * 2) hex.append(bytes * 2 - hex.size(), '0');
    return hex;
}

